// Generates the platform icon sprite of the local GUI from the website's icon set, so `tmaegis gui` shows the
// same product logos as www.tmaegis.dev without any network access.
//
//   node internal/gui/tools/gen-platform-icons.mjs           (or `go generate ./internal/gui`)
//   node internal/gui/tools/gen-platform-icons.mjs --check   (exit 1 when the committed output is stale)
//
// Inputs (read only):
//   web-portal/lib/platform-icons.ts   logos (simple-icons and SVG Logos, CC0, and the logos vendored in
//                                      web-portal/scripts/logos), brand colours and the target -> icon table,
//                                      itself generated by web-portal/scripts/gen-icons.mjs (which documents the
//                                      source of every logo; scripts/logos/logos.json records each vendored one)
//   web-portal/node_modules/lucide-react the eight generic glyphs (ISC) the website draws for brands without a logo
// Outputs (committed, embedded in the binary):
//   internal/gui/assets/platform-icons.svg   one <symbol> per logo, glyph and monogram
//   internal/gui/assets/platform-icons.json  target id -> symbol id, and each logo's colour where it has contrast
//
// Full-colour logos keep their own colours (on a contrasting chip in a theme where they would vanish, as on the
// website). Single-colour marks stay currentColor; their brand colour is only shown on hover or for a selected
// item, and only where it reaches 3:1 against every background the GUI draws an icon on in that theme
// (WCAG 1.4.11).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..", "..", "..");
const srcTS = path.join(repo, "web-portal", "lib", "platform-icons.ts");
const lucideDir = path.join(repo, "web-portal", "node_modules", "lucide-react", "dist", "esm", "icons");
const outSVG = path.join(here, "..", "assets", "platform-icons.svg");
const outJSON = path.join(here, "..", "assets", "platform-icons.json");
const check = process.argv.includes("--check");

// ---------- read the website's generated module (one JSON value per line) ----------
const ts = fs.readFileSync(srcTS, "utf8");
function table(name) {
  const start = ts.indexOf(`export const ${name}:`);
  if (start < 0) throw new Error(`${srcTS}: no ${name}`);
  const body = ts.slice(ts.indexOf("{\n", start) + 2, ts.indexOf("\n};", start));
  const out = {};
  for (const line of body.split("\n")) {
    const m = /^\s*("[^"]+"):\s*(.+?),?\s*$/.exec(line);
    if (!m) throw new Error(`${name}: cannot parse ${JSON.stringify(line)}`);
    out[JSON.parse(m[1])] = JSON.parse(m[2]);
  }
  return out;
}
const BRAND_ICONS = table("BRAND_ICONS");
const BRAND_SVG = table("BRAND_SVG");
const PLATFORM_ICONS = table("PLATFORM_ICONS");
const header = /^\/\/ Generated by scripts\/gen-icons\.mjs from (.+?)\. Do not edit/m.exec(ts);
const credit = header ? header[1] : "simple-icons, CC0 1.0";

// ---------- generic glyphs: the same lucide icons as web-portal/components/platform-icon.tsx ----------
const GLYPHS = { windows: "layout-grid", sun: "sun", key: "key-round", shield: "shield-check", code: "code", link: "link-2", printer: "printer", terminal: "terminal" };
let lucideVersion = "";
async function glyphNode(name) {
  const file = path.join(lucideDir, GLYPHS[name] + ".mjs");
  if (!fs.existsSync(file)) throw new Error(`${file} is missing: run \`npm ci\` in web-portal first`);
  if (!lucideVersion) lucideVersion = JSON.parse(fs.readFileSync(path.join(lucideDir, "..", "..", "..", "package.json"), "utf8")).version;
  const mod = await import(pathToFileURL(file).href);
  const data = mod.__iconData || {};
  const node = data.node || mod.__iconNode;
  if (!Array.isArray(node)) throw new Error(`${file}: no icon node`);
  return node;
}
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/"/g, "&quot;");
const el = (tag, attrs) => `<${tag}${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => ` ${k}="${esc(v)}"`).join("")}/>`;

// ---------- contrast (WCAG 2.x relative luminance) ----------
const lum = (hex) => {
  const c = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
// --bg, --card-solid, --muted (icon tiles) and the selected card (--primary-soft over --card-solid) of
// internal/gui/assets/style.css.
const DARK = ["0b0f19", "111827", "151d2e", "0f3241"];
const LIGHT = ["f5f9fd", "ffffff", "e9f1f8", "e6f0f6"];
const okOn = (hex, bgs) => bgs.every((bg) => ratio(hex, bg) >= 3);

// ---------- build ----------
// Monogram letters: unframed for a tile (larger), framed when drawn inline next to text, as on the website.
const monoSize = (text, framed) => (framed ? [0, 11.5, 10, 8][text.length] ?? 7 : [0, 15, 12.5, 10][text.length] ?? 9);
const monoSymbol = (id, text, framed) =>
  `<symbol id="${id}" viewBox="0 0 24 24">` +
  (framed ? '<rect x="2.75" y="2.75" width="18.5" height="18.5" rx="5" fill="none" stroke="currentColor" stroke-width="1.6"/>' : "") +
  `<text x="12" y="12.6" text-anchor="middle" dominant-baseline="middle" font-size="${monoSize(text, framed)}" font-weight="600" letter-spacing="-.3" fill="currentColor">${esc(text)}</text></symbol>`;
const monoId = (text) => "m-" + text.replace(/[^A-Za-z0-9]/g, "_");

const targets = {};
const brands = {};
const symbols = new Map(); // id -> markup, in output order
const brandSlugs = [...new Set(Object.values(PLATFORM_ICONS).flatMap((v) => (v.brand ? [v.brand] : [])))].sort();
for (const slug of brandSlugs) {
  const b = BRAND_ICONS[slug], svg = BRAND_SVG[slug];
  if (!b || !svg) throw new Error(`no logo data for "${slug}"`);
  symbols.set(slug, `<symbol id="${slug}" viewBox="0 0 24 24">${svg}</symbol>`);
  if (b.color) {
    // full colour: never recoloured; the chip themes come from the website's contrast check
    brands[slug] = { title: b.title, hex: b.hex, color: true, ...(b.chip ? { chip: b.chip } : {}), ...(b.wide ? { wide: true } : {}) };
    continue;
  }
  const dark = okOn(b.hex, DARK), light = okOn(b.hex, LIGHT);
  brands[slug] = { title: b.title, hex: b.hex, ...(b.wide ? { wide: true } : {}), ...(dark ? { dark: true } : {}), ...(light ? { light: true } : {}) };
}
for (const name of Object.keys(GLYPHS).filter((g) => Object.values(PLATFORM_ICONS).some((v) => v.glyph === g))) {
  const kids = (await glyphNode(name)).map(([tag, attrs]) => el(tag, attrs)).join("");
  symbols.set("g-" + name, `<symbol id="g-${name}" viewBox="0 0 24 24"><g fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${kids}</g></symbol>`);
}
for (const text of [...new Set(Object.values(PLATFORM_ICONS).flatMap((v) => (v.mono ? [v.mono] : [])))].sort()) {
  symbols.set(monoId(text), monoSymbol(monoId(text), text, false));
  symbols.set("mf-" + monoId(text).slice(2), monoSymbol("mf-" + monoId(text).slice(2), text, true));
}
for (const [id, ref] of Object.entries(PLATFORM_ICONS)) {
  const sym = ref.brand ? ref.brand : ref.glyph ? "g-" + ref.glyph : ref.mono ? monoId(ref.mono) : null;
  if (!sym || !symbols.has(sym)) throw new Error(`target "${id}": unsupported icon ${JSON.stringify(ref)}`);
  targets[id] = sym;
}

const note = `Generated by internal/gui/tools/gen-platform-icons.mjs from web-portal/lib/platform-icons.ts (${credit}) and lucide-react ${lucideVersion} (ISC). Do not edit; re-run the script.`;
const tm = "Product names, logos and brands are property of their respective owners and are used only to identify supported platforms.";
const sprite = ['<svg xmlns="http://www.w3.org/2000/svg">', `<!-- ${note} ${tm} -->`, ...symbols.values(), "</svg>", ""].join("\n");
const json = JSON.stringify({ note: note + " " + tm, targets, brands }, null, 1) + "\n";

if (check) {
  const stale = [[outSVG, sprite], [outJSON, json]].filter(([f, want]) => !fs.existsSync(f) || fs.readFileSync(f, "utf8") !== want);
  if (stale.length) {
    console.error("gen-platform-icons: stale output, re-run the script: " + stale.map(([f]) => path.relative(repo, f)).join(", "));
    process.exit(1);
  }
  console.log("gen-platform-icons: up to date");
} else {
  fs.writeFileSync(outSVG, sprite);
  fs.writeFileSync(outJSON, json);
  console.log(`gen-platform-icons: ${Object.keys(targets).length} targets, ${symbols.size} symbols (${brandSlugs.length} logos) -> ${path.relative(repo, outSVG)} (${sprite.length} bytes), ${path.relative(repo, outJSON)} (${json.length} bytes)`);
}
