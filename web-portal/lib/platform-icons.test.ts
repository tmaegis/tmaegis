import fs from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { BRAND_ICONS, BRAND_SVG, PLATFORM_ICONS, SPRITE_URL } from "./platform-icons";
import { PLATFORM_GROUPS, WORKS_WITH } from "./platforms";
import { TARGETS } from "./targets";

describe("platform icons (generated by scripts/gen-icons.mjs)", () => {
  it("every scan target has an icon (add it to ICONS in scripts/gen-icons.mjs and re-run it)", () => {
    const missing = Object.keys(TARGETS).filter((id) => !PLATFORM_ICONS[id]);
    expect(missing).toEqual([]);
  });

  it("every icon the home page and the download tabs name exists", () => {
    const ids = [...PLATFORM_GROUPS.flatMap((g) => g.items.map(([, icon]) => icon)), ...WORKS_WITH.map(([, icon]) => icon), "unix", "source", "riscv", "s390x"];
    for (const id of ids) expect(PLATFORM_ICONS[id], id).toBeDefined();
  });

  it("brand references resolve, and fallbacks are short monograms or known glyphs", () => {
    for (const [id, ref] of Object.entries(PLATFORM_ICONS)) {
      if ("brand" in ref) expect(BRAND_ICONS[ref.brand], id).toBeDefined();
      else if ("mono" in ref) expect(ref.mono.length, id).toBeLessThanOrEqual(3);
      else expect(["windows", "sun", "key", "shield", "code", "link", "printer", "terminal"], id).toContain(ref.glyph);
    }
  });

  it("holds only the logos in use, with valid colours, sources and markup", () => {
    const used = new Set(Object.values(PLATFORM_ICONS).flatMap((r) => ("brand" in r ? [r.brand] : [])));
    expect(Object.keys(BRAND_ICONS).sort()).toEqual([...used].sort());
    for (const [slug, b] of Object.entries(BRAND_ICONS)) {
      expect(b.hex, slug).toMatch(/^[0-9A-F]{6}$/);
      expect(b.source, slug).toMatch(/^(si|si-legacy|logos|vendor):[a-z0-9-]+$/);
      const svg = BRAND_SVG[slug as keyof typeof BRAND_SVG];
      if (b.color) {
        // full-colour logos: never recoloured, fitted into the 24 x 24 box, no active content, ids scoped to the symbol
        expect(b.dark || b.light, slug).toBe(false);
        expect(svg, slug).toMatch(/^<g fill="#000" transform="matrix\([-\d. ]+\)">/);
        expect(svg, slug).not.toMatch(/<(script|image|foreignObject|style)\b|\son\w+=/i);
        for (const [, id] of svg.matchAll(/\sid="([^"]+)"/g)) expect(id.startsWith(slug + "-"), `${slug}: ${id}`).toBe(true);
        if (b.chip) expect(b.chip, slug).toMatch(/^(dark|light)( light)?$/);
      } else {
        expect(svg, slug).toMatch(/^<path d="[Mm][-\d.][MmLlHhVvCcSsQqTtAaZz\d.\s-]*"\/>$/);
      }
    }
  });

  it("uses no simple-icons mark that carries its own (non-CC0) licence", () => {
    // Exchange and SharePoint are under the Fluent UI assets licence in simple-icons 9: they come from Wikimedia Commons.
    expect(PLATFORM_ICONS.exchange).toEqual({ brand: "v-microsoft-exchange" });
    expect(PLATFORM_ICONS.sharepoint).toEqual({ brand: "v-microsoft-sharepoint" });
    const sources = Object.values(BRAND_ICONS).map((b) => b.source);
    for (const s of ["si-legacy:microsoftexchange", "si-legacy:microsoftsharepoint"]) expect(sources).not.toContain(s);
  });

  it("documents every vendored logo in scripts/logos/logos.json, and vendors none that is unused", () => {
    const dir = path.join(import.meta.dirname, "..", "scripts", "logos");
    const meta = JSON.parse(fs.readFileSync(path.join(dir, "logos.json"), "utf8")) as Record<string, { title?: string; source?: string; license?: string; retrieved?: string }>;
    const files = fs.readdirSync(dir).filter((f) => f.endsWith(".svg")).map((f) => f.slice(0, -4)).sort();
    const used = Object.values(BRAND_ICONS).flatMap((b) => (b.source.startsWith("vendor:") ? [b.source.slice(7)] : [])).sort();
    expect(files).toEqual(used);
    expect(Object.keys(meta).filter((k) => !k.startsWith("_")).sort()).toEqual(files);
    for (const name of files) {
      const m = meta[name];
      expect(m.title && m.license, name).toBeTruthy();
      expect(m.source, name).toMatch(/^https:\/\//);
      expect(m.retrieved, name).toMatch(/^\d{4}-\d{2}-\d{2}$/);
      const svg = fs.readFileSync(path.join(dir, name + ".svg"), "utf8");
      expect(svg, name).toMatch(/^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg"[^>]* viewBox="[-\d. ]+"[^>]*>/);
      expect(svg, name).not.toMatch(/<(script|image|foreignObject|style|a)\b|\son\w+=|href="(?!#)|url\((?!#)/i);
    }
  });

  it("puts a full-colour logo on a chip only where its own colours would vanish", () => {
    expect(BRAND_ICONS["l-aws"].chip).toBe("dark"); // the dark "aws" lettering
    expect(BRAND_ICONS["v-arista"].chip).toBe("dark"); // navy wordmark
    // light letters on the logo's own tile, translucent highlights and faded stops do not count
    for (const slug of ["l-aws-eks", "v-microsoft-exchange", "v-microsoft-sharepoint", "v-microsoft-power-platform", "l-visual-studio-code"] as const) expect(BRAND_ICONS[slug].chip, slug).toBeUndefined();
  });

  it("gives every product with a mark in an open collection its logo (fallbacks only where none exists)", () => {
    const fallbacks = Object.entries(PLATFORM_ICONS).filter(([, r]) => !("brand" in r)).map(([id]) => id).sort();
    expect(fallbacks).toEqual(["extreme-slx", "kerberos", "oceanbase", "printer", "source", "supply-chain", "unix"]);
  });

  it("matches the committed sprite in public/ (re-run scripts/gen-icons.mjs when this fails)", () => {
    expect(SPRITE_URL).toMatch(/^\/platform-icons\.[0-9a-f]{10}\.svg$/);
    const pub = path.join(import.meta.dirname, "..", "public");
    expect(fs.readdirSync(pub).filter((f) => f.startsWith("platform-icons."))).toEqual([SPRITE_URL.slice(1)]);
    const sprite = fs.readFileSync(path.join(pub, SPRITE_URL.slice(1)), "utf8");
    for (const [slug, svg] of Object.entries(BRAND_SVG)) expect(sprite, slug).toContain(`<symbol id="${slug}" viewBox="0 0 24 24">${svg}</symbol>`);
    expect(sprite.match(/<symbol /g)).toHaveLength(Object.keys(BRAND_SVG).length);
    expect(sprite).toContain("used only to identify supported platforms");
  });

  it("is not imported from an icon package at runtime", () => {
    const pkg = JSON.parse(fs.readFileSync(path.join(import.meta.dirname, "..", "package.json"), "utf8")) as { dependencies: Record<string, string>; devDependencies: Record<string, string> };
    for (const name of ["simple-icons", "simple-icons-legacy", "@iconify-json/logos"]) {
      expect(pkg.dependencies[name], name).toBeUndefined();
      expect(pkg.devDependencies[name], name).toBeDefined();
    }
  });
});
